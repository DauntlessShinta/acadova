const mongoose = require('mongoose');

const SessionSchema = new mongoose.Schema({
  // Explicitly set by request creation, never defaulted onto historical records.
  lifecycleVersion: { type: Number, enum: [1], immutable: true },
  expProcessedAt: Date,
  expOutcome: {type:String,enum:['recorded','ineligible']},
  learner: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  tutor: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
  subject: { type: String, required: true, trim: true },
  scheduledAt: { type: Date },
  proposedScheduledAt: { type: Date },
  rescheduleProposedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
  rescheduleProposedAt: { type: Date },
  rescheduleProposalId: { type: String },
  rescheduleExpiresAt: { type: Date },
  rescheduleHistory: { type: [new mongoose.Schema({
    proposalId: { type: String, required: true },
    outcome: { type: String, enum: ['accepted', 'declined', 'withdrawn', 'replaced', 'expired', 'check_in_locked'], required: true },
    actor: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    at: { type: Date, required: true }, scheduledAt: Date, proposedScheduledAt: Date, expiresAt: Date,
  }, { _id: false })], default: undefined },
  learnerCheckedInAt: { type: Date },
  tutorCheckedInAt: { type: Date },
  startedAt: { type: Date },
  awaitingValidationAt: { type: Date },
  validationDeadlineAt: Date,
  validationReminderMarks: { type: [String], default: undefined },
  reviewVersion: { type: Number, min: 0 },
  reviewReferral: { type: new mongoose.Schema({
    id: { type: String, required: true },
    source: { type: String, enum: ['system_overdue', 'tutor_request', 'legacy_tutor_request'], required: true },
    reason: { type: String, required: true, maxlength: 500 },
    requestedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
    createdAt: { type: Date, required: true }, targetAt: { type: Date, required: true },
    escalatedAt: Date, closedAt: Date,
    closure: { type: String, enum: ['participant_completion', 'staff_resolution'] },
  }, { _id: false }) },
  completionEvidence: { type: [new mongoose.Schema({
    id: { type: String, required: true },
    submittedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    submittedAt: { type: Date, required: true },
    summary: { type: String, required: true, maxlength: 1000 },
    completedWork: { type: String, required: true, maxlength: 2000 },
    links: { type: [String], validate: (value) => value.length <= 5 },
  }, { _id: false })], default: undefined },
  reviewClarifications: { type: [new mongoose.Schema({
    id: { type: String, required: true },
    requestedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', required: true },
    requestedAt: { type: Date, required: true },
    reason: { type: String, required: true, maxlength: 500 },
  }, { _id: false })], default: undefined },
  learnerConfirmedAt: { type: Date },
  tutorConfirmedAt: { type: Date },
  noShowAt: { type: Date },
  noShowReportedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
  noShowAbsent: { type: String, enum: ['learner', 'tutor', 'both'] },
  disputedAt: { type: Date },
  disputedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
  disputeReason: { type: String, trim: true, maxlength: 500 },
  resolvedAt: { type: Date },
  resolvedBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
  resolution: { type: String, enum: ['confirm_session', 'cancel_session'] },
  resolutionNote: { type: String, trim: true, maxlength: 500 },
  meetingMethod: { type: String, enum: ['online', 'in-person'] },
  meetingLink: { type: String, trim: true, maxlength: 500 },
  location: { type: String, trim: true, maxlength: 300 },
  requestMessage: { type: String, trim: true, maxlength: 500 },
  status: {
    type: String,
    enum: ['pending', 'accepted', 'scheduled', 'in_progress', 'awaiting_validation', 'rejected', 'declined', 'completed', 'cancelled', 'no_show', 'disputed', 'resolved'],
    default: 'pending',
  },
  economyVersion: { type:String, enum:['free-v1'], immutable:true },
  creditAmount: { type:Number, required:true, validate:{ validator(value) { return Number.isSafeInteger(value) && (this.economyVersion==='free-v1'?value===0:value>=1); }, message:'Invalid session economy evidence.' } },
  validationSettledAt: Date,
  legacyObligationResolvedAt: Date,
  legacyObligationReview: {type:mongoose.Schema.Types.ObjectId,ref:'LegacyCreditReview'},
  expReport: { type:new mongoose.Schema({ reporter:{type:mongoose.Schema.Types.ObjectId,ref:'User'}, reason:{type:String,maxlength:500}, reportedAt:Date, status:{type:String,enum:['open','dismissed','upheld']}, resolvedBy:{type:mongoose.Schema.Types.ObjectId,ref:'User'}, resolvedAt:Date, resolutionReason:{type:String,maxlength:500} },{_id:false}), select:false },
  completedAt: { type: Date },
  confirmedAt: { type: Date },
  creditsSettledAt: { type: Date },
}, { timestamps: true, autoIndex: process.env.NODE_ENV !== 'production' });

// Speeds up "my sessions" and subject-demand analytics queries.
SessionSchema.index({ learner: 1 });
SessionSchema.index({ tutor: 1 });
SessionSchema.index({ subject: 1 });

module.exports = mongoose.model('Session', SessionSchema);
